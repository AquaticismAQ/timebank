package cn.timebank.common.web;

import java.util.Optional;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.boot.info.BuildProperties;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Contract §4.17. `version` comes from {@link BuildProperties}, which Spring
 * Boot auto-configures from the {@code build-info} goal's
 * {@code META-INF/build-info.properties} (see pom.xml's
 * spring-boot-maven-plugin execution) — this class never hand-maintains a
 * version string. Injected as an {@link ObjectProvider} rather than
 * required, since that file is only generated by a real {@code mvn
 * package}; a bare {@code mvn spring-boot:run} outside this repo's normal
 * package-then-deploy flow would otherwise crash the whole app at startup
 * over a version-display nicety.
 */
@RestController
public class SystemVersionController {

    private final ObjectProvider<BuildProperties> buildProperties;

    public SystemVersionController(ObjectProvider<BuildProperties> buildProperties) {
        this.buildProperties = buildProperties;
    }

    @GetMapping("/api/v1/system/version")
    @PreAuthorize("isAuthenticated()")
    public ApiResponse<SystemVersionDto> getVersion() {
        String version = Optional.ofNullable(buildProperties.getIfAvailable())
                .map(BuildProperties::getVersion)
                .orElse("dev");
        return ApiResponse.of(new SystemVersionDto(version));
    }

    public record SystemVersionDto(String version) {
    }
}
