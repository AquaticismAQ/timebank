#!/usr/bin/env bash
# Workstation wrapper for TimeBank maintenance mode — syncs the real logic
# (timebank-maintctl) to the server and runs it there. All the actual
# on/off/schedule/status behavior lives in that one script; this is just
# the SSH plumbing, matching ops/maintenance/deploy.sh's own shape.
#
# Usage:
#   ops/maintenance/maintctl.sh on
#   ops/maintenance/maintctl.sh off
#   ops/maintenance/maintctl.sh schedule [--start HH:MM] [--end HH:MM]
#   ops/maintenance/maintctl.sh status
#
# `status` additionally writes/refreshes MAINTENANCE_ACCESS.md in the repo
# root (gitignored — see .gitignore) with a ready-to-click bypass link if
# the site is currently gated, or a plain "not gated right now" note if
# not — a plain-text place to grab the link from without re-running this
# or digging the key back out of ~/.timebank.env.
#
# Requires ops/maintenance/deploy.sh to have been run at least once first
# (creates /var/www/timebank-maintenance/, the nginx snippet, and the base
# systemd units this script customizes).
set -euo pipefail
cd "$(dirname "$0")"

if [ -f "$HOME/.timebank.env" ]; then
  # shellcheck disable=SC1090,SC1091
  source "$HOME/.timebank.env"
fi

if [ $# -eq 0 ]; then
  echo "Usage: $0 {on|off|schedule [--start HH:MM] [--end HH:MM]|status}" >&2
  exit 1
fi

TARGET="${TIMEBANK_DEPLOY_TARGET:-root@tb.example.com}"
REPO_ROOT="$(cd ../.. && pwd)"
ACCESS_FILE="${REPO_ROOT}/MAINTENANCE_ACCESS.md"

rsync -az timebank-maintctl "${TARGET}:/usr/local/sbin/timebank-maintctl"

if [ "$1" = "status" ]; then
  OUTPUT="$(ssh "${TARGET}" "chmod +x /usr/local/sbin/timebank-maintctl && /usr/local/sbin/timebank-maintctl $(printf '%q ' "$@")")"
  echo "$OUTPUT"

  BASE_URL="${TIMEBANK_BASE_URL:-https://tb.example.com}"
  TIMESTAMP="$(date '+%Y-%m-%d %H:%M %Z')"

  if echo "$OUTPUT" | grep -q "Gate: ACTIVE"; then
    if [ -z "${TIMEBANK_MAINTENANCE_BYPASS_KEY:-}" ]; then
      echo
      echo "maintctl.sh: gate is ACTIVE but TIMEBANK_MAINTENANCE_BYPASS_KEY isn't set locally — can't write the bypass link to $ACCESS_FILE." >&2
    else
      cat > "$ACCESS_FILE" <<EOF
# Maintenance bypass link

Local only — gitignored, never commit (it embeds the real bypass key).
Generated by \`ops/maintenance/maintctl.sh status\` — $TIMESTAMP.

## Site is currently GATED

Open this once in any browser to set a 30-day bypass cookie and get
straight into the app from then on:

${BASE_URL}/__ops/enter?key=${TIMEBANK_MAINTENANCE_BYPASS_KEY}

Re-run \`ops/maintenance/maintctl.sh status\` any time to refresh this file.
EOF
      echo
      echo "maintctl.sh: site is gated — bypass link written to $ACCESS_FILE"
    fi
  else
    cat > "$ACCESS_FILE" <<EOF
# Maintenance bypass link

Local only — gitignored, never commit.
Checked by \`ops/maintenance/maintctl.sh status\` — $TIMESTAMP.

## Site is currently NOT gated

No bypass link needed right now — $BASE_URL is reachable normally.
EOF
    echo
    echo "maintctl.sh: site is not currently in maintenance mode."
  fi
else
  ssh "${TARGET}" "chmod +x /usr/local/sbin/timebank-maintctl && /usr/local/sbin/timebank-maintctl $(printf '%q ' "$@")"
fi
